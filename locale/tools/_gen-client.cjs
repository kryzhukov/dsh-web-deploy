'use strict';
const fs = require('fs');
const path = require('path');

const dictFile = path.join(__dirname, '_ru_dicts_en.json');
const cacheFile = path.join(__dirname, '_ru_cache.json');
// Works in both layouts: the deployed ~/.dsh/ru-locale-tools and the repo's
// locale/tools next to locale/dsh-locale-ru.
const deployedLib = path.join(__dirname, '..', 'profiles', 'web', 'locale-ru', 'lib');
const repoLib = path.join(__dirname, '..', 'dsh-locale-ru', 'lib');
const outFile = path.join(fs.existsSync(deployedLib) ? deployedLib : repoLib, 'client.js');

const dicts = JSON.parse(fs.readFileSync(dictFile, 'utf8'));
const cache = JSON.parse(fs.readFileSync(cacheFile, 'utf8'));

// Hand-tuned overrides for the strings users meet first (Google is literal
// without UI context, so the most visible labels are curated here).
const overrides = {
  'Stop generating': 'Остановить генерацию',
  'Describe what you want to build, / commands, @ files or sessions':
    'Опишите, что хотите создать; / — команды, @ — файлы и сессии',
  'Message or run a task, / commands, @ files or sessions':
    'Сообщение или задача; / — команды, @ — файлы и сессии',
  'Standard mode': 'Стандартный режим',
  'Minimal mode': 'Минимальный режим',
  'Creator mode': 'Режим создателя',
  'PTC mode': 'Режим PTC',
  'Workspace Write': 'Запись в рабочей области',
  'Approval details': 'Детали подтверждения',
  'Search automation tasks': 'Поиск задач автоматизации',
  'Agent presets': 'Пресеты агентов',
  'High': 'Высокий',
  'Medium': 'Средний',
  'Low': 'Низкий',
  'New Session': 'Новый чат',
  'Settings': 'Настройки',
  'Preview': 'Предпросмотр',
  'Appearance': 'Внешний вид',
  'Light': 'Светлая',
  'Dark': 'Тёмная',
  'System': 'Системная',
  'Close': 'Закрыть',
  'Detailed': 'Подробно',
  'Queue': 'Очередь',
};

// Context-specific overrides: the chat/tool step chips are narrated in the
// first person ("Думаю", "Читаю", "Редактирую"), while the same English words
// stay infinitive on ordinary buttons ("Редактировать").
const byKey = {
  'chat/message.think': 'Думаю',
  'trajectory/column.think': 'Думаю',
  'conversation/tool.title.read': 'Читаю',
  'conversation/tool.title.edit': 'Редактирую',
  'conversation/tool.title.write': 'Пишу',
  'conversation/tool.title.readImage': 'Читаю изображение',
};

const ru = {};
let translated = 0;
let keptEnglish = 0;
for (const d of dicts) {
  const namespace = {};
  for (const [key, value] of Object.entries(d.en)) {
    const candidate = byKey[`${d.ns}/${key}`] ?? overrides[value] ?? cache[value];
    if (typeof candidate === 'string' && candidate.trim() !== '' && candidate !== value) {
      namespace[key] = candidate;
      translated++;
    } else {
      keptEnglish++;
    }
  }
  if (Object.keys(namespace).length > 0) ru[d.ns] = namespace;
}

const banner = `/**
 * Russian language pack for the DeepSeek Harness Web UI.
 *
 * Generated by _gen-client.cjs from the English dictionaries shipped with
 * DSH ${new Date().toISOString().slice(0, 10)}; ${translated} keys translated, ${keptEnglish} left to the English fallback.
 * Edit translations in _ru_cache.json (or the overrides map) and regenerate.
 */
`;

const client = `window.__ModuleLoader__.load({
\tid: "dsh-locale-ru",
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

${banner}
\t\tconst ru = ${JSON.stringify(ru, null, '\t')};

\t\tconst inject = ["locale"];

\t\tfunction apply(ctx) {
\t\t\tctx.effect(
\t\t\t\t() => ctx.locale.addLanguage({ id: "ru", label: "Русский", fallback: "en" }),
\t\t\t\t"locale-ru: language"
\t\t\t);
\t\t\tfor (const [ns, dict] of Object.entries(ru)) {
\t\t\t\tctx.effect(
\t\t\t\t\t() => ctx.locale.register(ns, "ru", dict),
\t\t\t\t\t"locale-ru: " + ns
\t\t\t\t);
\t\t\t}
\t\t}

\t\texports.apply = apply;
\t\texports.inject = inject;
\t\treturn module.exports;
\t}
});
`;

fs.writeFileSync(outFile, client, 'utf8');
console.log(`namespaces=${Object.keys(ru).length} translated=${translated} fallback=${keptEnglish} bytes=${Buffer.byteLength(client)}`);
